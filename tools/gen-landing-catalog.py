#!/usr/bin/env python3
"""Writes the ring data for the landing page (wolfgang-linz.de/orbo) from the real catalog.

Usage: gen-landing-catalog.py <output.js>
"""
import glob
import json
import os
import re
import sys

import yaml

ROOT = os.path.join(os.path.dirname(__file__), '..', 'core', 'crates', 'orbo-core')
SRC = open(os.path.join(ROOT, 'src', 'format.rs')).read()

KIND_IDS = {'Image': 'image', 'Video': 'video', 'Audio': 'audio', 'Document': 'document', 'Data': 'data',
            'Archive': 'archive', 'Model': 'model', 'Cad': 'cad', 'Font': 'typeface', 'Folder': 'folder', 'Other': 'other'}


def fn_body(name):
    start = SRC.index(f'pub fn {name}(')
    return SRC[start:SRC.index('\n    }\n', start)]


def fmt_id(variant):
    rename = re.search(r'#\[serde\(rename = "([^"]+)"\)\]\s*' + variant + r'\b', SRC)
    return rename.group(1) if rename else variant.lower()


ext_map = {}
for pats, variant in re.findall(r'^\s*((?:"[^"]+"\s*\|?\s*)+)=>\s*(\w+),', fn_body('from_extension'), re.M):
    for e in re.findall(r'"([^"]+)"', pats):
        ext_map[e] = fmt_id(variant)

fmt_kind = {}
for variants, kind in re.findall(r'^\s*([\w| ]+?)\s*=>\s*Kind::(\w+),', fn_body('kind'), re.M):
    for v in variants.split('|'):
        fmt_kind[fmt_id(v.strip())] = KIND_IDS[kind]

cat = os.path.join(ROOT, 'catalog')
targets, ring_fmt, ring_kind = {}, {}, {}
for path in sorted(glob.glob(os.path.join(cat, 'targets*.yaml'))):
    for t in (yaml.safe_load(open(path)) or {}).get('targets') or []:
        out = t.get('output', '')
        kind = 'archive' if out == 'folder' else fmt_kind.get(out, 'document')
        presets = [p['label'] for p in t.get('presets') or []]
        targets[t['id']] = [t['title'], t.get('sub', ''), kind, presets, t.get('accepts') or []]
for path in sorted(glob.glob(os.path.join(cat, 'rules*.yaml'))):
    ring = (yaml.safe_load(open(path)) or {}).get('ring') or {}
    ring_fmt.update(ring.get('format') or {})
    ring_kind.update(ring.get('kind') or {})


def accepts(tid, fmt):
    acc = targets[tid][4]
    return fmt in acc or fmt_kind.get(fmt) in acc


rings = {}
for fmt, kind in fmt_kind.items():
    ids = [i for i in ring_fmt.get(fmt, []) if i in targets]
    for i in ring_kind.get(kind, []):
        if len(ids) >= 6:
            break
        if i in targets and i not in ids and accepts(i, fmt):
            ids.append(i)
    if ids:
        rings[fmt] = ids[:6]

data = {
    'targets': {k: v[:4] for k, v in targets.items()},
    'rings': rings,
    'ext': ext_map,
    'kind': fmt_kind,
}
with open(sys.argv[1], 'w') as f:
    f.write('// Generated by Orbo/tools/gen-landing-catalog.py from the app catalog. Do not edit.\n')
    f.write('window.ORBO_CATALOG = ' + json.dumps(data, ensure_ascii=False, separators=(',', ':')) + ';\n')
print(f'{len(targets)} Ziele, {len(rings)} Formate mit Ring, {len(ext_map)} Endungen')
